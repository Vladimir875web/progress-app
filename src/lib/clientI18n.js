export function getClientTranslation(lang, key) {
  const pack = messages[lang] || messages.ru;
  return pack[key] ?? messages.ru[key] ?? key;
}

export function fmtClientDate(iso, lang) {
  const locale = DATE_LOCALES[lang] || DATE_LOCALES.ru;
  return new Date(iso + "T00:00:00").toLocaleDateString(locale, {
    day: "2-digit", month: "2-digit", year: "2-digit",
  });
}

export function weightDeltaHint(delta, lang) {
  const sign = delta > 0 ? "+" : "";
  const unit = getClientTranslation(lang, "kg");
  if (lang === "en") return `${sign}${delta}${unit} from start`;
  if (lang === "cs") return `${sign}${delta} ${unit} od startu`;
  return `${sign}${delta}${unit} от старта`;
}

export function bmiLabelText(bmi, t) {
  const v = parseFloat(bmi);
  if (v < 18.5) return t("bmiUnder");
  if (v < 25) return t("bmiNormal");
  if (v < 30) return t("bmiOver");
  return t("bmiObese");
}
